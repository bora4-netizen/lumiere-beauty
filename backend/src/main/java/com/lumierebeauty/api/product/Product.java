package com.lumierebeauty.api.product;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.Id;
import jakarta.persistence.PrePersist;
import jakarta.persistence.Table;
import org.springframework.data.domain.Persistable;

import java.math.BigDecimal;
import java.time.Instant;

/**
 * A catalogue row: serum, blush, fragrance...
 * The id uses the frontend convention (e.g. "P-1001") instead of a
 * database number so the UI keeps working with the same values.
 *
 * Implements Persistable so Spring Data treats a product without a
 * createdAt timestamp as new (INSERT instead of UPDATE): ids are assigned
 * by the service, not generated by the database.
 */
@Entity
@Table(name = "products")
public class Product implements Persistable<String> {

    public static final String STATUS_ACTIVE = "Active";
    public static final String STATUS_DRAFT = "Draft";

    @Id
    @Column(length = 20)
    private String id;

    @Column(nullable = false, length = 150)
    private String name;

    @Column(nullable = false, length = 100)
    private String brand;

    @Column(nullable = false, length = 100)
    private String category;

    @Column(nullable = false, precision = 10, scale = 2)
    private BigDecimal price;

    @Column(length = 1000)
    private String description;

    @Column(length = 500)
    private String imageUrl;

    @Column(nullable = false)
    private int stock;

    @Column(nullable = false, length = 20)
    private String status;

    @Column(nullable = false)
    private boolean featured;

    @Column(name = "created_at", nullable = false)
    private Instant createdAt;

    public Product() {
    }

    @PrePersist
    void onCreate() {
        if (createdAt == null) {
            createdAt = Instant.now();
        }
    }

    public String getId() {
        return id;
    }

    public void setId(String id) {
        this.id = id;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getBrand() {
        return brand;
    }

    public void setBrand(String brand) {
        this.brand = brand;
    }

    public String getCategory() {
        return category;
    }

    public void setCategory(String category) {
        this.category = category;
    }

    public BigDecimal getPrice() {
        return price;
    }

    public void setPrice(BigDecimal price) {
        this.price = price;
    }

    public String getDescription() {
        return description;
    }

    public void setDescription(String description) {
        this.description = description;
    }

    public String getImageUrl() {
        return imageUrl;
    }

    public void setImageUrl(String imageUrl) {
        this.imageUrl = imageUrl;
    }

    public int getStock() {
        return stock;
    }

    public void setStock(int stock) {
        this.stock = stock;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        // Normalize capitalization so "active" and "Active" behave the same.
        if (STATUS_DRAFT.equalsIgnoreCase(status)) {
            this.status = STATUS_DRAFT;
        } else {
            this.status = STATUS_ACTIVE;
        }
    }

    public boolean isFeatured() {
        return featured;
    }

    public void setFeatured(boolean featured) {
        this.featured = featured;
    }

    public Instant getCreatedAt() {
        return createdAt;
    }

    /** A product without createdAt has not been saved yet — see Persistable. */
    @Override
    public boolean isNew() {
        return createdAt == null;
    }
}
